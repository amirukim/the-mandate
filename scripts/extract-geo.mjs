/**
 * Build-time extractor: turns Natural Earth country polygons into a typed
 * SVG path module for the federation and diplomacy maps.
 *
 * Input:  geojson from nvkelso/natural-earth-vector (public domain)
 * Output: src/data/geo-paths.ts — quantized point arrays, no runtime cost.
 *
 * Run:  node scripts/extract-geo.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const cache = process.env.NE_CACHE ?? join(here, "..", "..", "..", "Temp", "opencode", "ne-cache");
const source = join(cache, "ne_50m_admin_0_countries.geojson");
const out = join(here, "..", "src", "data", "geo-paths.ts");

const TARGETS = [
  "Malaysia",
  "Indonesia",
  "Singapore",
  "Thailand",
  "Vietnam",
  "Philippines",
  "Brunei",
  "China",
  "Taiwan",
  "Papua New Guinea",
  "East Timor",
];

const geo = JSON.parse(readFileSync(source, "utf8"));

/** Equirectangular projection around the SEA bounding box, y flipped. */
const LON0 = 92, LON1 = 132, LAT0 = -12, LAT1 = 30;
const W = 1200, H = 640;
const px = (lon) => ((lon - LON0) / (LON1 - LON0)) * W;
const py = (lat) => H - ((lat - LAT0) / (LAT1 - LAT0)) * H;

const picked = {};
for (const f of geo.features) {
  const name = f.properties?.ADMIN ?? f.properties?.NAME;
  if (!TARGETS.includes(name)) continue;
  const rings = [];
  const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.type === "MultiPolygon" ? f.geometry.coordinates : [];
  for (const poly of polys) {
    for (const ring of poly) {
      // quantize to integers; drop degenerate segments
      const pts = [];
      let last = null;
      for (const [lon, lat] of ring) {
        const p = [Math.round(px(lon)), Math.round(py(lat))];
        if (last && p[0] === last[0] && p[1] === last[1]) continue;
        pts.push(p);
        last = p;
      }
      if (pts.length > 3) rings.push(pts);
    }
  }
  if (rings.length) {
    picked[name] = picked[name] ? picked[name].concat(rings) : rings;
  }
}

let ts = `/**
 * Auto-generated by scripts/extract-geo.mjs from Natural Earth 1:50m
 * country polygons (public domain, nvkelso/natural-earth-vector).
 * Quantized equirectangular projection over 92-132E, -12 to 30N into
 * a 1200x640 viewbox. Do not edit by hand; re-run the script to refresh.
 */
export type GeoRing = readonly (readonly [number, number])[];

export const GEO_VIEWBOX = { width: 1200, height: 640, lon0: ${LON0}, lon1: ${LON1}, lat0: ${LAT0}, lat1: ${LAT1} } as const;

`;

for (const [name, rings] of Object.entries(picked)) {
  const id = name.replace(/[^A-Za-z0-9]+/g, "_");
  const body = rings
    .map((r) => `    [${r.map((p) => `[${p[0]},${p[1]}]`).join(", ")}],`)
    .join("\n");
  ts += `export const GEO_${id}: GeoRing[] = [\n${body}\n];\n\n`;
}

writeFileSync(out, ts);
const total = Object.values(picked).reduce((n, r) => n + r.length, 0);
const points = Object.values(picked).reduce((n, rs) => n + rs.reduce((m, r) => m + r.length, 0), 0);
console.log(`wrote ${out}`);
console.log(`countries: ${Object.keys(picked).length}, rings: ${total}, points: ${points}`);
